import { readFile, writeFile, access, mkdir, readdir, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const packs = JSON.parse(await readFile(path.join(root, 'data/quizzes.json'), 'utf8'));
const locale = JSON.parse(await readFile(path.join(root, 'data/locales/sr-Cyrl.json'), 'utf8'));
const text = (key) => {
  const value = locale.messages[key];
  if (typeof value !== 'string' || !value.trim()) throw new Error(`Missing translation: ${key}`);
  return value;
};
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const lines = ['-- Generated by scripts/generate-content.mjs. Do not edit by hand.'];
const quizIDs = new Set();
for (const pack of packs) {
  if (quizIDs.has(pack.id)) throw new Error(`Duplicate quiz: ${pack.id}`);
  quizIDs.add(pack.id);
  lines.push(`INSERT INTO quizzes(id,title,prompt,description) VALUES (${[pack.id, ...['title', 'prompt', 'description'].map((field) => text(`quiz.${pack.id}.${field}`))].map(quote)}) ON CONFLICT(id) DO UPDATE SET title=excluded.title,prompt=excluded.prompt,description=excluded.description;`);
  const subjects = JSON.parse(await readFile(path.join(root, `data/${pack.file}.json`), 'utf8'));
  if (subjects.length < 4) throw new Error(`${pack.id} needs four subjects`);
  const ids = new Set(), labels = new Set();
  const values = [];
  for (const subject of subjects) {
    const label = text(`answer.${pack.id}.${subject.id}`);
    if (!subject.id || ids.has(subject.id) || labels.has(label)) throw new Error(`Invalid/duplicate subject: ${pack.id}/${subject.id}`);
    if (!/^\/(flags|animals|plants|dogs|traffic|sports|shapes)\/[a-zA-Z0-9_.-]+$/.test(subject.image_url)) throw new Error(`Invalid image: ${subject.image_url}`);
    await access(path.join(root, 'web', subject.image_url));
    ids.add(subject.id); labels.add(label);
    values.push(`(${[pack.id, subject.id, label, subject.image_url].map(quote)})`);
  }
  lines.push(`INSERT INTO questions(quiz_id,id,label,image_url) VALUES ${values.join(',')} ON CONFLICT(quiz_id,id) DO UPDATE SET label=excluded.label,image_url=excluded.image_url;`);
}
const sql = `${lines.join('\n')}\n`;
const target = path.join(root, 'data/seed.sql');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== sql) throw new Error('Content migration is stale. Run npm run content:generate.');
} else {
  await writeFile(target, sql);
}

// Each locale owns its text and recordings; IDs never depend on translated wording.
for (const name of (await readdir(path.join(root, 'data/locales'))).filter((name) => name.endsWith('.json'))) {
  const source = JSON.parse(await readFile(path.join(root, 'data/locales', name), 'utf8'));
  if (!/^[a-zA-Z0-9-]+$/.test(source.locale) || name !== `${source.locale}.json`) throw new Error(`Invalid locale: ${name}`);
  for (const key of Object.keys(locale.messages)) {
    if (typeof source.messages[key] !== 'string' || !source.messages[key].trim()) throw new Error(`Missing ${source.locale} translation: ${key}`);
  }
  const audio = {};
  for (const [key, value] of Object.entries(source.messages)) {
    if (!source.voice) continue;
    if (!(key.startsWith('answer.') || key.startsWith('quiz.') && key.endsWith('.prompt'))) continue;
    const hash = createHash('sha256').update(JSON.stringify([source.locale, source.voice, source.rate, value])).digest('hex').slice(0, 24);
    audio[key] = `/audio/${source.locale}/${hash}.mp3`;
    if (process.argv.includes('--check') && (await stat(path.join(root, 'web', audio[key]))).size < 1000) throw new Error(`Empty audio: ${key}`);
  }
  const generated = `${JSON.stringify({ ...source, audio }, null, 2)}\n`;
  const output = path.join(root, 'web/locales', name);
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== generated) throw new Error(`Stale locale: ${name}. Run npm run content:generate.`);
  } else {
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, generated);
  }
}

await import('./generate-ui.mjs');
