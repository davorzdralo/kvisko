import { readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const packs = JSON.parse(await readFile(path.join(root, 'data/quizzes.json'), 'utf8'));
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const lines = ['-- Generated by scripts/generate-content.mjs. Do not edit by hand.'];
const quizIDs = new Set();
for (const pack of packs) {
  if (quizIDs.has(pack.id)) throw new Error(`Duplicate quiz: ${pack.id}`);
  quizIDs.add(pack.id);
  lines.push(`INSERT INTO quizzes(id,title,prompt,description) VALUES (${[pack.id, pack.title, pack.prompt, pack.description].map(quote)}) ON CONFLICT(id) DO UPDATE SET title=excluded.title,prompt=excluded.prompt,description=excluded.description;`);
  const subjects = JSON.parse(await readFile(path.join(root, `data/${pack.file}.json`), 'utf8'));
  if (subjects.length < 4) throw new Error(`${pack.id} needs four subjects`);
  const ids = new Set(), labels = new Set();
  const values = [];
  for (const subject of subjects) {
    if (!subject.id || !subject.label || ids.has(subject.id) || labels.has(subject.label)) throw new Error(`Invalid/duplicate subject: ${pack.id}/${subject.id}`);
    if (!/^\/(flags|animals|plants|dogs|traffic)\/[a-zA-Z0-9_.-]+$/.test(subject.image_url)) throw new Error(`Invalid image: ${subject.image_url}`);
    await access(path.join(root, 'web', subject.image_url));
    ids.add(subject.id); labels.add(subject.label);
    values.push(`(${[pack.id, subject.id, subject.label, subject.image_url].map(quote)})`);
  }
  lines.push(`INSERT INTO questions(quiz_id,id,label,image_url) VALUES ${values.join(',')} ON CONFLICT(quiz_id,id) DO UPDATE SET label=excluded.label,image_url=excluded.image_url;`);
}
const sql = `${lines.join('\n')}\n`;
const target = path.join(root, 'data/seed.sql');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== sql) throw new Error('Content migration is stale. Run npm run content:generate.');
} else {
  await writeFile(target, sql);
}
